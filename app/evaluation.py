"""Compare analyzer diagnoses with the ground truth in sample-logs/scenarios.json."""

import json
import time
from collections import Counter
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Protocol

from app.parser import ParsedLog, parse_log
from app.schemas import LLMDiagnosis


class Analyzer(Protocol):
    model: str

    def diagnose(self, parsed: ParsedLog, pipeline: str | None) -> LLMDiagnosis: ...


@dataclass
class ScenarioResult:
    scenario_id: str
    pipeline: str | None
    root_error: str | None
    expected_error_type: str
    expected_severity: str
    expected_root_cause: str
    error_type: str | None = None
    severity: str | None = None
    probable_cause: str | None = None
    recommendation: str | None = None
    failure: str | None = None
    seconds: float = 0.0

    @property
    def error_type_ok(self) -> bool:
        return self.error_type == self.expected_error_type

    @property
    def severity_ok(self) -> bool:
        return self.severity == self.expected_severity


@dataclass
class Summary:
    model: str
    total: int
    error_type_correct: int
    severity_correct: int
    both_correct: int
    failures: int
    mean_seconds: float
    error_type_confusion: dict[str, int]
    severity_confusion: dict[str, int]


def load_scenarios(sample_logs: Path) -> list[dict]:
    return json.loads((sample_logs / "scenarios.json").read_text())


def evaluate_scenario(analyzer: Analyzer, scenario: dict, log_text: str) -> ScenarioResult:
    parsed = parse_log(log_text)
    expected = scenario["expected"]
    result = ScenarioResult(
        scenario_id=scenario["id"],
        pipeline=parsed.pipeline,
        root_error=parsed.root_error,
        expected_error_type=expected["error_type"],
        expected_severity=expected["severity"],
        expected_root_cause=expected["root_cause"],
    )
    start = time.perf_counter()
    try:
        diagnosis = analyzer.diagnose(parsed, parsed.pipeline)
    except Exception as exc:  # one failing scenario must not stop the evaluation
        result.failure = f"{type(exc).__name__}: {exc}"
    else:
        result.error_type = diagnosis.error_type.value
        result.severity = diagnosis.severity.value
        result.probable_cause = diagnosis.probable_cause
        result.recommendation = diagnosis.recommendation
    result.seconds = round(time.perf_counter() - start, 2)
    return result


def evaluate(analyzer: Analyzer, sample_logs: Path) -> list[ScenarioResult]:
    return [
        evaluate_scenario(analyzer, scenario, (sample_logs / f"{scenario['id']}.log").read_text())
        for scenario in load_scenarios(sample_logs)
    ]


def summarize(results: list[ScenarioResult], model: str) -> Summary:
    def confusion(expected_attr: str, actual_attr: str) -> dict[str, int]:
        pairs = Counter(
            f"{getattr(r, expected_attr)} -> {getattr(r, actual_attr)}"
            for r in results
            if getattr(r, expected_attr) != getattr(r, actual_attr)
        )
        return dict(sorted(pairs.items()))

    total = len(results)
    return Summary(
        model=model,
        total=total,
        error_type_correct=sum(r.error_type_ok for r in results),
        severity_correct=sum(r.severity_ok for r in results),
        both_correct=sum(r.error_type_ok and r.severity_ok for r in results),
        failures=sum(r.failure is not None for r in results),
        mean_seconds=round(sum(r.seconds for r in results) / total, 2) if total else 0.0,
        error_type_confusion=confusion("expected_error_type", "error_type"),
        severity_confusion=confusion("expected_severity", "severity"),
    )


def to_json(results: list[ScenarioResult], summary: Summary) -> str:
    return json.dumps({"summary": asdict(summary), "results": [asdict(r) for r in results]}, indent=2) + "\n"


def _pct(part: int, total: int) -> str:
    return f"{part}/{total} ({part / total:.0%})" if total else "0/0"


def _cell(text: str | None) -> str:
    return (text or "—").replace("|", "\\|").replace("\n", " ")


def _mark(ok: bool) -> str:
    return "✅" if ok else "❌"


def to_markdown(results: list[ScenarioResult], summary: Summary) -> str:
    lines = [
        "# Evaluation report",
        "",
        f"Model: `{summary.model}` · scenarios: {summary.total} · "
        "ground truth: `sample-logs/scenarios.json` · generated by `scripts/evaluate.py`.",
        "",
        "## Summary",
        "",
        "| Metric | Result |",
        "| --- | --- |",
        f"| error_type accuracy | {_pct(summary.error_type_correct, summary.total)} |",
        f"| severity accuracy | {_pct(summary.severity_correct, summary.total)} |",
        f"| both correct | {_pct(summary.both_correct, summary.total)} |",
        f"| failed calls | {summary.failures} |",
        f"| mean latency | {summary.mean_seconds} s |",
        "",
    ]
    for title, confusion in (
        ("error_type mistakes", summary.error_type_confusion),
        ("severity mistakes", summary.severity_confusion),
    ):
        lines += [f"## {title} (expected -> predicted)", ""]
        lines += [f"- `{pair}`: {count}" for pair, count in confusion.items()] or ["- none"]
        lines.append("")

    lines += [
        "## Per scenario",
        "",
        "| Scenario | error_type (expected / predicted) | severity (expected / predicted) | s |",
        "| --- | --- | --- | --- |",
    ]
    for r in results:
        lines.append(
            f"| {r.scenario_id} | {_mark(r.error_type_ok)} {r.expected_error_type} / {r.error_type or 'n/a'} "
            f"| {_mark(r.severity_ok)} {r.expected_severity} / {r.severity or 'n/a'} | {r.seconds} |"
        )
    lines += ["", "## Root cause: expected vs model (manual review)", ""]
    for r in results:
        lines += [
            f"### {r.scenario_id}",
            "",
            f"- **Root error (parser):** {_cell(r.root_error)}",
            f"- **Expected cause:** {_cell(r.expected_root_cause)}",
            f"- **Model cause:** {_cell(r.probable_cause or r.failure)}",
            f"- **Model recommendation:** {_cell(r.recommendation)}",
            "",
        ]
    return "\n".join(lines)
